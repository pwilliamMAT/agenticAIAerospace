function radar = createCharacterizedRadar()
%CREATECHARACTERIZEDRADAR Create a synthetic Exercise 2 radar stand-in.
%   This temporary model has the same measurement modes required by
%   Exercise 3, but intentionally differs from the baseline ground radar.
%   Replace this file with the Radar Designer App output when available.

elevationAccuracy = atan2d(1.2, 420);
elevationBiasFraction = 0.05;

radar = radarDataGenerator(1, ...
    UpdateRate=1, ...
    FieldOfView=[24; 18], ...
    HasElevation=true, ...
    ScanMode="Mechanical", ...
    MechanicalAzimuthLimits=[0 360], ...
    MechanicalElevationLimits=[-18+1e-3 0], ...
    HasINS=true, ...
    HasRangeRate=true, ...
    HasNoise=true, ...
    HasFalseAlarms=true, ...
    DetectionProbability=0.78, ...
    ReferenceRange=275000, ...
    ReferenceRCS=10, ...
    RangeLimits=[0 420000], ...
    AzimuthResolution=3.2, ...
    AzimuthBiasFraction=0.08, ...
    ElevationResolution=elevationAccuracy/elevationBiasFraction, ...
    ElevationBiasFraction=elevationBiasFraction, ...
    RangeResolution=450, ...
    RangeBiasFraction=150/450, ...
    RangeRateResolution=120, ...
    FalseAlarmRate=1e-7, ...
    RangeRateLimits=[-450 450], ...
    DetectionCoordinates="Sensor spherical");
end
